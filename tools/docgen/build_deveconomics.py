"""Generate the DigitalSecretary DevEconomics workbook (per-activity cost + time ledger).

Single source of truth = this script's data tables. Captures EVERY activity Claude performs to
build a feature, classified by cost bucket, with token/cost and time, plus a per-feature summary
that tracks ESTIMATE vs ACTUAL and a trend chart.

Cost buckets:
  A = LLM tokens (the only metered cost)   B = local compute ($0)   C = remote/network ($0)

Outputs:
  docs/deveconomics/DigitalSecretary-DevEconomics.xlsx

Run:  python tools/docgen/build_deveconomics.py

Notes on truth: token/cost for LLM rows are ESTIMATES (the model can't read its own meter). Local
times are MEASURED from command output where captured, else estimated. Replace per-feature ACTUAL
cost with the figure from `/cost` (Claude Code) or the Anthropic Console, then re-run.
"""
