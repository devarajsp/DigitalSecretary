THIN = Side(style="thin", color="D9D9D9")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
A_FILL = PatternFill("solid", fgColor="FCE4D6")  # LLM (cost) - warm
B_FILL = PatternFill("solid", fgColor="E2EFDA")  # local ($0) - green
C_FILL = PatternFill("solid", fgColor="DDEBF7")  # remote ($0) - blue

